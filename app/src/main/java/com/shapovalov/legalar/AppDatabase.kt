@Database(
    entities = [LegalReference::class],
    version = AppDatabase.VERSION,
    exportSchema = false
)
abstract class AppDatabase : RoomDatabase() {

    abstract fun legalDao(): LegalDao

    companion object {

        const val VERSION = 1

        private const val DATABASE_NAME = "legal_ar.db"

        @Volatile
        private var instance: AppDatabase? = null

        fun getInstance(context: Context): AppDatabase {
            val existing = instance
            if (existing != null) {
                return existing
            }
            synchronized(this) {
                val created = instance ?: buildDatabase(context.applicationContext)
                instance = created
                return created
            }
        }

        private fun buildDatabase(context: Context): AppDatabase {
            return Room.databaseBuilder(context, AppDatabase::class.java, DATABASE_NAME)
                .addCallback(SeedCallback())
                .fallbackToDestructiveMigration()
                .build()
        }
    }

    private class SeedCallback : RoomDatabase.Callback() {

        override fun onCreate(db: SupportSQLiteDatabase) {
            super.onCreate(db)
            seed(db)
        }

        override fun onOpen(db: SupportSQLiteDatabase) {
            super.onOpen(db)
            seed(db)
        }

        private fun seed(db: SupportSQLiteDatabase) {
            if (rowCount(db) > 0) {
                return
            }
            for (reference in SeedCatalog.references()) {
                db.insert(
                    LegalReference.TABLE_NAME,
                    SQLiteDatabase.CONFLICT_IGNORE,
                    SeedCatalog.contentValues(reference)
                )
            }
        }

        private fun rowCount(db: SupportSQLiteDatabase): Int {
            val cursor = db.query("SELECT COUNT(*) FROM " + LegalReference.TABLE_NAME)
            cursor.use {
                if (it.moveToFirst()) {
                    return it.getInt(0)
                }
            }
            return 0
        }
    }
}
